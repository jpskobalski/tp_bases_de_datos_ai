    ds.decision_id,
    fr.feature_id,
    CASE fr.nombre
        WHEN 'tx_count_5m' THEN
            CASE WHEN ds.score_riesgo >= 0.60 THEN '8' ELSE '2' END
        WHEN 'amount_sum_1h' THEN ip.monto::TEXT
        WHEN 'reject_count_24h' THEN
            CASE WHEN ds.score_riesgo >= 0.60 THEN '4' ELSE '0' END
        WHEN 'distinct_payers_24h' THEN
            CASE WHEN ds.score_riesgo >= 0.60 THEN '5' ELSE '1' END
        WHEN 'reject_rate_24h' THEN
            CASE WHEN ds.score_riesgo >= 0.60 THEN '0.35' ELSE '0.05' END
    END,
    ip.fecha_hora
FROM decision_scoring ds
JOIN intento_pago ip ON ip.intento_id = ds.intento_id
CROSS JOIN feature_riesgo fr;

